"""PlanX runtime algorithm matrix: execute every algorithm on a live runtime.

Run it with a QGIS launcher, not with a bare Python::

    C:/OSGeo4W/bin/python-qgis-ltr.bat planx/tests/qgis_runtime_algorithm_matrix.py
    C:/OSGeo4W/bin/python-qgis.bat     planx/tests/qgis_runtime_algorithm_matrix.py

Why this exists
---------------
``smoke_provider_catalog.py`` proves the *catalogue* is coherent - ids, groups,
icons, manual anchors. ``smoke_plugin.py`` loads the plugin and counts
algorithms. Neither runs an algorithm. Neither would notice a tool that raises
on every call, returns without writing its sink, or loses its outputs between
QGIS releases. "Does it load?" is not a test (TRAPS 5.1); this matrix answers
the next question a user asks: "does it run?".

What a green cell means - and what it does not
----------------------------------------------
Each case feeds one algorithm a fixture city generated by ``planx:democity``,
executes it through the Processing framework, and asserts that every declared
output was produced and carries data. A green cell therefore means: *the
algorithm was instantiated, accepted its declared parameters, ran to
completion, and emitted populated outputs on this runtime.*

A green cell does **not** prove the numbers are right. Inputs are wired from
each algorithm's own ``parameterDefinitions()`` - see :func:`_pick_layer`,
:func:`_pick_field` and :func:`_pick_raster` - rather than from 69 hand-written
per-algorithm cases, because a hand-written table silently rots when a parameter
is added. The cost of that choice is that a cell can pass while a parameter was
wired to a defensible-but-wrong fixture. Where the name is ambiguous or two
fixtures are equally plausible, the choice is pinned in ``LAYER_OVERRIDES`` /
``FIELD_BY_PARAM`` / ``RASTER_BY_PARAM``.

Numerical correctness is the job of the engine unit tests (``test_engine.py``)
and of ``smoke_plugin.py``, which checks published figures against their
sources. This matrix is the execution-and-plumbing gate. The one structural
claim it does make about values is that a vector output must contain at least
one feature and a raster output at least one finite, non-nodata pixel - so
"ran but produced nothing" is red, not green.

Every wiring decision for every parameter is recorded in the JSON the run
prints, so those claims are checkable rather than asserted.
"""
