def _write_layer(path, name, fields, wkb_type, crs, rows, transform_context):
    """Write one GeoPackage layer from already-built (geometry, attributes)."""
    options = QgsVectorFileWriter.SaveVectorOptions()
    options.driverName = "GPKG"
    options.layerName = name
    writer = QgsVectorFileWriter.create(
        str(path), fields, wkb_type, crs, transform_context, options)
    if writer is None:
        raise RuntimeError(f"could not create a writer for {path}")
    for geometry, attributes in rows:
        feature = QgsFeature()
        feature.setGeometry(geometry)
        feature.setAttributes(attributes)
        writer.addFeature(feature)
    del writer  # flushes and closes the dataset
    if not Path(path).exists():
        raise RuntimeError(f"{path} was not written")
    return str(path)


def _augment(source, name, extra, attributes_for, out_dir, transform_context):
    """Copy ``source`` into ``out_dir`` with ``extra`` fields appended."""
    fields = QgsFields()
    for field in source.fields():
        fields.append(QgsField(field))
    for field_name, value_type in extra:
        fields.append(QgsField(field_name, value_type))

    names = [field.name().lower() for field in source.fields()]
    rows = []
    for index, feature in enumerate(source.getFeatures()):
        attributes = list(feature.attributes())
        by_name = dict(zip(names, attributes))
        rows.append((feature.geometry(),
                     attributes + attributes_for(index, feature, by_name)))
    path = Path(out_dir) / f"{name}.gpkg"
    _write_layer(path, name, fields, source.wkbType(), source.crs(), rows,
                 transform_context)
    return path


def _bounding_layer(name, extent, crs, out_dir, transform_context):
    fields = QgsFields()
    fields.append(QgsField("area_m2", DOUBLE))
    polygon = QgsGeometry.fromRect(extent)
    rows = [(polygon, [float(extent.width() * extent.height())])]
    path = Path(out_dir) / f"{name}.gpkg"
    return Path(_write_layer(path, name, fields, QgsWkbTypes.Type.Polygon, crs,
                             rows, transform_context))


def _write_gtfs(demand_layer, crs, out_path, transform_context):
    """A minimal but valid GTFS feed whose stops sit on the demo city.

    Placed on real demand points rather than at arbitrary coordinates: a feed
    thousands of kilometres away would still parse, and every transit case would
    go green while proving nothing (TRAPS 5.2).
    """
    transform = QgsCoordinateTransform(
        crs, QgsCoordinateReferenceSystem("EPSG:4326"), transform_context)

    stops = []
    for feature in demand_layer.getFeatures():
        geometry = feature.geometry()
        if geometry is None or geometry.isEmpty():
            continue
        lon_lat = transform.transform(geometry.asPoint())
        stops.append((lon_lat.x(), lon_lat.y()))
        if len(stops) == 8:
            break
    if len(stops) < 4:
        raise RuntimeError("demo city produced too few demand points for a GTFS feed")

    lines = {
        "stops.txt": "stop_id,stop_name,stop_lat,stop_lon\n" + "".join(
            f"S{i},Stop {i},{lat:.6f},{lon:.6f}\n"
            for i, (lon, lat) in enumerate(stops)),
        "routes.txt": "route_id,route_short_name,route_long_name,route_type\n"
                      "R1,1,Line 1,3\n",
        "trips.txt": "route_id,service_id,trip_id\nR1,WK,T1\n",
        "stop_times.txt": "trip_id,arrival_time,departure_time,stop_id,"
                          "stop_sequence\n" + "".join(
            f"T1,{8 + i // 12:02d}:{i * 5 % 60:02d}:00,"
            f"{8 + i // 12:02d}:{i * 5 % 60:02d}:00,S{i},{i + 1}\n"
            for i in range(len(stops))),
        "calendar.txt": "service_id,monday,tuesday,wednesday,thursday,friday,"
                        "saturday,sunday,start_date,end_date\n"
                        "WK,1,1,1,1,1,0,0,20260101,20261231\n",
    }
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for file_name, text in lines.items():
            archive.writestr(file_name, text)


def _write_raster(path, array, template):
    from osgeo import gdal

    _source, geotransform, projection = template
    rows, cols = array.shape
    driver = gdal.GetDriverByName("GTiff")
    handle = driver.Create(str(path), cols, rows, 1, gdal.GDT_Float32,
                           options=["COMPRESS=LZW"])
    handle.SetGeoTransform(geotransform)
    if projection:
        handle.SetProjection(projection)
    band = handle.GetRasterBand(1)
    band.SetNoDataValue(-9999.0)
    band.WriteArray(array)
    band.FlushCache()
    handle = None
    return str(path)


def _classify(dsm, threshold, above=1.0, below=0.0):
    import numpy as np

    out = np.where(np.isfinite(dsm), below, -9999.0)
    out[np.isfinite(dsm) & (dsm > threshold)] = above
    return out


def build_fixtures(processing, work_dir, transform_context):
    """Run ``planx:democity`` and widen its outputs into the fixture bundle."""
    import numpy as np

    from planx.algorithms._raster import read_dsm

    raw_dir = Path(work_dir) / "raw"
    raw_dir.mkdir(parents=True, exist_ok=True)

    raw = processing.run("planx:democity", {
        "SEED": CITY_SEED,
        "BLOCKS_X": CITY_BLOCKS_X,
        "BLOCKS_Y": CITY_BLOCKS_Y,
        "BLOCK_SIZE": CITY_BLOCK_SIZE,
        "CRS": CITY_CRS,
        "OUTPUT_STREETS": str(raw_dir / "streets.gpkg"),
        "OUTPUT_BUILDINGS": str(raw_dir / "buildings.gpkg"),
        "OUTPUT_LANDUSE": str(raw_dir / "landuse.gpkg"),
        "OUTPUT_POIS": str(raw_dir / "pois.gpkg"),
        "OUTPUT_FACILITIES": str(raw_dir / "facilities.gpkg"),
        "OUTPUT_DEMAND": str(raw_dir / "demand.gpkg"),
        "OUTPUT_GREEN": str(raw_dir / "green.gpkg"),
        "OUTPUT_DSM": str(raw_dir / "dsm.tif"),
    })

    def load(key):
        layer = QgsVectorLayer(str(raw[key]), key, "ogr")
        if not layer.isValid():
            raise RuntimeError(f"demo output '{key}' did not load")
        return layer

    fix_dir = Path(work_dir) / "fixtures"
    fix_dir.mkdir(parents=True, exist_ok=True)

    layers = {
        "network": _augment(load("OUTPUT_STREETS"), "network", NETWORK_EXTRA,
                            _network_attrs, fix_dir, transform_context),
        "buildings": _augment(load("OUTPUT_BUILDINGS"), "buildings",
                              BUILDINGS_EXTRA, _building_attrs, fix_dir,
                              transform_context),
        "landuse": _augment(load("OUTPUT_LANDUSE"), "landuse", LANDUSE_EXTRA,
                            _landuse_attrs, fix_dir, transform_context),
        "demand": _augment(load("OUTPUT_DEMAND"), "demand", DEMAND_EXTRA,
                           _demand_attrs, fix_dir, transform_context),
        "pois": _augment(load("OUTPUT_POIS"), "pois", POIS_EXTRA,
                         _poi_attrs, fix_dir, transform_context),
        "facilities": _augment(load("OUTPUT_FACILITIES"), "facilities",
                               FACILITIES_EXTRA, _facility_attrs, fix_dir,
                               transform_context),
        "green": _augment(load("OUTPUT_GREEN"), "green", GREEN_EXTRA,
                          _green_attrs, fix_dir, transform_context),
        "flows": _augment(load("OUTPUT_STREETS"), "flows", FLOWS_EXTRA,
                          _flows_attrs, fix_dir, transform_context),
    }
    # PARCELS is the land-use polygons again: the tools that take PARCELS want
    # an area field and per-use suitability columns, which this layer carries.
    layers["parcels"] = layers["landuse"]

    parcels = QgsVectorLayer(str(layers["landuse"]), "landuse", "ogr")
    study_area = _bounding_layer("study_area", parcels.extent(), parcels.crs(),
                                 fix_dir, transform_context)

    dsm_layer = QgsRasterLayer(str(raw["OUTPUT_DSM"]), "dsm", "gdal")
    if not dsm_layer.isValid():
        raise RuntimeError("demo DSM did not load")
    dsm, geotransform, projection, _pixel = read_dsm(dsm_layer)
    finite = dsm[np.isfinite(dsm)]
    if finite.size == 0:
        raise RuntimeError("demo DSM has no finite cells")

    template = (dsm, geotransform, projection)
    rasters = {
        # A city DSM stands in wherever a tool wants a terrain DEM. That proves
        # the plumbing, not the geomorphology: real hydrology wants real relief.
        "dsm": str(raw["OUTPUT_DSM"]),
        "dem": str(raw["OUTPUT_DSM"]),
        "inundation": _write_raster(
            fix_dir / "inundation.tif",
            _classify(dsm, float(np.percentile(finite, 25.0)), 1.0, 0.0),
            template),
        "urban_t1": _write_raster(
            fix_dir / "urban_t1.tif",
            _classify(dsm, float(np.percentile(finite, 50.0)), 1.0, 0.0),
            template),
        "urban_t2": _write_raster(
            fix_dir / "urban_t2.tif",
            _classify(dsm, float(np.percentile(finite, 40.0)), 1.0, 0.0),
            template),
        "seed": _write_raster(
            fix_dir / "seed.tif",
            _classify(dsm, float(np.percentile(finite, 75.0)), 1.0, 0.0),
            template),
        "constraints": _write_raster(
            fix_dir / "constraints.tif",
            _classify(dsm, float(np.percentile(finite, 90.0)), 1.0, 0.0),
            template),
        "suitability": _write_raster(
            fix_dir / "suitability.tif",
            np.where(np.isfinite(dsm),
                     (dsm - finite.min()) / (float(finite.max() - finite.min()) or 1.0),
                     -9999.0),
            template),
    }

    # Land-cover change needs integer class rasters, not 0/1 masks: a change
    # matrix between two two-valued rasters is trivially symmetric and would
    # pass without testing anything.
    edges = [float(np.percentile(finite, p)) for p in (0, 25, 50, 75, 100)]
    classes_t1 = np.full(dsm.shape, -9999.0)
    classes_t2 = np.full(dsm.shape, -9999.0)
    for band in range(4):
        inside = (np.isfinite(dsm) & (dsm >= edges[band])
                  & (dsm < edges[band + 1]) if band < 3
                  else np.isfinite(dsm) & (dsm >= edges[band]))
        classes_t1[inside] = band + 1
        classes_t2[inside] = min(4, band + 2)  # T2 shifts a band, so cells change
    rasters["landcover_t1"] = _write_raster(fix_dir / "landcover_t1.tif",
                                            classes_t1, template)
    rasters["landcover_t2"] = _write_raster(fix_dir / "landcover_t2.tif",
                                            classes_t2, template)

    demand_layer = QgsVectorLayer(str(layers["demand"]), "demand", "ogr")
    gtfs_path = fix_dir / "demo_gtfs.zip"
    _write_gtfs(demand_layer, parcels.crs(), gtfs_path, transform_context)

    return {
        "layers": layers,
        "study_area": study_area,
        "rasters": rasters,
        "files": {"gtfs": str(gtfs_path)},
        "raw": raw,
    }


