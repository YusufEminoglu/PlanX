# Everything above answers "did the tool produce something?". For most tools
# that is all a smoke matrix can honestly ask. For a tool that converts units
# it is not enough: planx:groundmotion once measured every distance in the
# receivers' own metres and fed it to a model that takes kilometres, so a demo
# city 750 m across reported receivers out to 472 km - and this matrix stayed
# green, because a number wrong by 1000x is still a number in a non-empty
# layer. Entries below are checks on the *values* of the demo run, and they
# belong wherever a silent factor of a thousand is the plausible failure.

DEMO_CITY_SPAN_KM = 0.75


def _read_gpkg(path):
    """``(column names, rows as dicts, complaint)`` for a written GeoPackage.

    Read with ``sqlite3``, never with a ``QgsVectorLayer`` - and that is the
    whole point of this function. **Reading attributes** out of a written
    GeoPackage through QGIS leaves the file held open for the rest of the
    process on Windows, and an open file cannot be deleted. The extra runs
    below re-create a destination that the primary run already wrote, so a
    value check that read its output through QGIS made the *next* run of that
    algorithm die with::

        Could not create layer ...gpkg: Creation of data source failed
        (OGR error: A file system object called '...gpkg' already exists.)

    Measured on 3.44, not guessed. With no prior read, re-creating the file
    succeeds and deleting it succeeds. So does a ``featureCount()`` - which is
    why this stayed hidden: ``_verify_vector`` counts every output and those
    files stayed replaceable. Iterating the features and reading one attribute
    is what locks it, and then nothing releases it - re-creating and deleting
    both fail with ``winerror 32`` for every release strategy tried (the
    wrapper kept, ``del``-ed, and ``del``-ed plus ``gc.collect()``).

    ``sqlite3`` holds no GDAL handle: the database is opened, read and closed
    inside this call, so the file stays exactly as replaceable as it was. It
    is also the honest reading - these columns are what any other program
    would find in the file, with no QGIS interpretation in between.

    A value check must return a complaint rather than a wrong number, so
    every way of failing to read the table - unreadable file, no feature
    table, more than one, no rows - is reported here.
    """
    uri = Path(path).resolve().as_uri() + "?mode=ro"
    try:
        connection = sqlite3.connect(uri, uri=True)
    except sqlite3.Error as exc:
        return None, None, f"could not open {path} as a GeoPackage: {exc}"
    try:
        connection.row_factory = sqlite3.Row
        tables = [row[0] for row in connection.execute(
            "SELECT table_name FROM gpkg_contents WHERE data_type = 'features'"
            " ORDER BY table_name")]
        if not tables:
            return None, None, f"{path} holds no feature table"
        if len(tables) > 1:
            return None, None, (
                f"{path} holds {len(tables)} feature tables ({', '.join(tables)}), "
                f"so a column cannot be read unambiguously")
        table = tables[0]
        names = [row["name"] for row in connection.execute(
            f'PRAGMA table_info("{table}")')]
        rows = [dict(row) for row in connection.execute(f'SELECT * FROM "{table}"')]
    except sqlite3.Error as exc:
        return None, None, f"could not read {path}: {exc}"
    finally:
        connection.close()
    if not rows:
        return names, rows, f"{path} holds no row to read a value from"
    return names, rows, None


def _expect_groundmotion_distances_are_kilometres(path):
    """The demo city is under a kilometre across, so no distance may be larger.

    The epicentre is the study area's point-on-surface - the centre of a
    ~750 m square - which puts every receiver well inside a kilometre of it.
    A ceiling far above the real geometry but far below the metre-reading of
    it (472 km) separates the two without pinning a figure that the fixture
    could legitimately move.

    Note what this case is not: every receiver is in the near field, where the
    model saturates at about 0.5 g, so it exercises the site term and the row
    indexing but not the distance decay. That belongs to the engine tests.
    """
    names, rows, complaint = _read_gpkg(path)
    if complaint:
        return complaint
    if "r_km_2" in names:
        # make_fields renames a computed column that would collide with an
        # input field of the same name, so the column called r_km here would
        # be the input's, not the tool's - the same way a fixture that already
        # carried `score` made every access metric read back identical. Fail
        # loudly rather than measure the wrong column.
        return (f"the layer carries both 'r_km' and 'r_km_2', so 'r_km' is an "
                f"input field and the computed distance was renamed: {names}")
    if "r_km" not in names:
        return "no r_km column to read a distance from"
    distances = []
    for row in rows:
        value = row["r_km"]
        if value is None:
            return "an r_km value is NULL"
        distances.append(float(value))
    if not distances:
        return "no receiver to read a distance from"
    worst = max(distances)
    ceiling = 10.0 * DEMO_CITY_SPAN_KM
    if not 0.0 < worst < ceiling:
        return (f"the furthest receiver is {worst:.3f} km from the epicentre, "
                f"but the demo city is only about {DEMO_CITY_SPAN_KM:g} km "
                f"across - the distances look like the CRS's own units being "
                f"passed off as kilometres")
    return None


def _expect_impact_casualties_conserve_occupants(path):
    """Casualties must be a share of the people the scenario puts in a building.

    A casualty count is a screening number with no external reference value to
    pin - but it has a hard ceiling. Hazus rates four severities against the
    occupants present at the scenario time, so the four counts can never sum
    above the occupant count, and a run that reports more injuries than people
    is wrong whichever way the rates were read. That is exactly the class of
    defect presence-verification cannot see: the layer is full, every field is
    populated, and the numbers are physically impossible.

    The ceiling needs a floor under it to mean anything, so the run must also
    put somebody in a building. Without that, zero occupants satisfies every
    bound - see the note at the end of this function.
    """
    names, rows, complaint = _read_gpkg(path)
    if complaint:
        return complaint
    names = set(names)
    required = {"occupants", "cas_sev1", "cas_sev2", "cas_sev3", "cas_sev4",
                "cas_total", "displaced_hh", "public_shelter"}
    missing = required - names
    if missing:
        return f"missing impact column(s): {', '.join(sorted(missing))}"
    if "occupants_2" in names:
        # make_fields renames a collision, so 'occupants' below would be a
        # column of the input layer, not this tool's.
        return (f"the layer carries both 'occupants' and 'occupants_2', so the "
                f"impact columns did not land where they should: {sorted(names)}")
    seen = 0
    modelled = 0.0
    for index, row in enumerate(rows, start=1):
        value = {name: row[name] for name in required}
        if any(item is None for item in value.values()):
            return f"a NULL impact value in row {index}"
        people = float(value["occupants"])
        modelled += people
        severities = [float(value[f"cas_sev{s}"]) for s in range(1, 5)]
        total = float(value["cas_total"])
        if abs(total - sum(severities)) > 1e-6:
            return (f"row {index}: cas_total {total:.6f} is not the sum of the "
                    f"four severities {sum(severities):.6f}")
        # Outdoor casualties are counted against the same occupant pool, so
        # the four severities are bounded by the occupants whoever they are.
        if sum(severities) > people + 1e-6:
            return (f"row {index}: {sum(severities):.3f} casualties from "
                    f"{people:.3f} occupants - more people hurt than the "
                    f"building holds, so the rates or the shares were misread")
        if float(value["displaced_hh"]) > people + 1e-6:
            return (f"row {index}: {value['displaced_hh']:.3f} displaced "
                    f"households from {people:.3f} occupants")
        if float(value["public_shelter"]) > people + 1e-6:
            return (f"row {index}: {value['public_shelter']:.3f} people seeking "
                    f"shelter from {people:.3f} occupants")
        seen += 1
    if not seen:
        return "no building to read an impact value from"
    if modelled <= 0.0:
        # Every bound above is a ceiling, so a run that puts nobody in any
        # building satisfies all of them and reports a city of nobody with a
        # clean sheet. That is not a hypothetical: it is how the point-centroid
        # output of planx:seismicdebris hid a zero occupant count from this
        # check while shelter still divided a default dwelling count by it.
        return (f"the run put {modelled:.3f} people in {seen} building(s), so "
                f"every casualty and shelter number above is bounded by zero "
                f"and checks nothing")
    return None


def _expect_debris_volume_uses_the_reported_footprint(path):
    """The debris volume must be built from the area the column reports.

    ``footprint_area`` was added so the arithmetic is checkable by hand:
    material = footprint x height x the solid share of the gross volume x the
    released fraction of the damage state. If the two numbers ever come from
    different areas the identity breaks feature by feature - and nothing else
    here would notice, because the counts, the geometry and both magnitudes
    stay entirely plausible.

    That is not hypothetical: the footprint was the layer's own
    ``QgsGeometry.area()`` until v4.15.1, which is square metres only on a
    metre-unit layer with no projection scale factor. Both tools now measure
    the geometry on the ellipsoid (``planx.algorithms._units``), so this check
    also stands between the reported column and a volume converted while the
    column is not.

    Read through :func:`_read_gpkg`, not through QGIS. This is the one
    expectation whose algorithm has an extra run that re-writes the very
    destination being checked, so holding a QGIS datasource here would make
    that extra run fail on Windows - see the reasoning there.
    """
    from planx.engine import seismic

    names, rows, complaint = _read_gpkg(path)
    if complaint:
        return complaint
    required = {"footprint_area", "height_m", "debris_vol_m3", "damage_state"}
    missing = required - set(names)
    if missing:
        return f"missing debris column(s): {', '.join(sorted(missing))}"
    algorithm = QgsApplication.processingRegistry().algorithmById("planx:seismicdebris")
    if algorithm is None:
        return "planx:seismicdebris is not registered, so its solid ratio is unknown"
    declared = float(algorithm.parameterDefinition("SOLID_VOLUME_RATIO").defaultValue())
    states = {name: index for index, name in enumerate(seismic.DAMAGE_STATES)}
    ratio = None
    for index, row in enumerate(rows, start=1):
        area = float(row["footprint_area"])
        height = float(row["height_m"])
        volume = float(row["debris_vol_m3"])
        state = row["damage_state"]
        if state not in states:
            return f"row {index}: unknown damage state {state!r}"
        factor = float(seismic.material_factor([states[state]])[0])
        if factor == 0.0:
            # slight and none shed nothing that reaches the street; a non-zero
            # volume there would be a different bug, as would dividing by it.
            if volume != 0.0:
                return (f"row {index}: {volume:.6f} m3 of debris from '{state}' "
                        f"damage, which releases no material")
            continue
        if area <= 0.0 or height <= 0.0:
            return f"row {index}: {area:.3f} m2 of footprint at {height:.3f} m"
        candidate = volume / (area * height * factor)
        if ratio is None:
            ratio = candidate
        elif abs(candidate - ratio) > 1e-6 * max(1.0, abs(ratio)):
            return (f"row {index}: material volume is {candidate:.6f} of footprint x "
                    f"height x state factor where an earlier row gave {ratio:.6f}, so "
                    f"the volume and the footprint_area column are not the same area")
    if ratio is None:
        return ("no building in {0} carried both a footprint and a damage state that "
                "releases material, so the volume identity checked nothing".format(
                    path))
    if abs(ratio - declared) > 1e-6:
        return (f"the material volume is {ratio:.6f} of footprint x height x state "
                f"factor where SOLID_VOLUME_RATIO declares {declared:.6f}")
    return None


def _expect_liquefaction_matches_its_own_terms(path):
    """The reported probability must equal the model evaluated on the row's own inputs.

    The output layer carries every term the model used - PGA, Mw, CTI, Vs30 -
    so the probability is reconstructible from the same file a reader gets.
    That is the check the output counts cannot make. A column wired to the
    wrong quantity, the two models' probabilities crossed, a probability
    carried through a clip the reported inputs never went through: each of
    those produces a plausible, monotone, fully populated layer, and each of
    them fails here.

    It also holds the *order* of the clip honest. The stored CTI is the raw
    grid value, so a row whose index was clipped to the model's ceiling
    reconstructs only if the tool clipped it in the same place this does -
    before the logarithm, not after.
    """
    from planx.engine import liquefaction

    names, rows, complaint = _read_gpkg(path)
    if complaint:
        return complaint
    required = {"liq_prob", "liq_area_frac", "pga_g", "mw", "cti", "vs30_ms"}
    missing = required - set(names)
    if missing:
        return f"missing liquefaction column(s): {', '.join(sorted(missing))}"
    checked = 0
    for index, row in enumerate(rows, start=1):
        if row["liq_prob"] in (None, ""):
            continue
        expected = liquefaction.zhu_probability(
            float(row["pga_g"]), float(row["mw"]),
            float(row["cti"]), float(row["vs30_ms"]))
        if abs(float(row["liq_prob"]) - expected["probability"]) > 1e-9:
            return (f"row {index}: liq_prob is {float(row['liq_prob']):.12f} where "
                    f"the row's own PGA/Mw/CTI/Vs30 give "
                    f"{expected['probability']:.12f}")
        if abs(float(row["liq_area_frac"]) - expected["coverage"]) > 1e-9:
            return (f"row {index}: liq_area_frac is not the 0.81 coverage reading "
                    "of liq_prob")
        checked += 1
    if not checked:
        return f"no row of {path} carried a probability, so nothing was checked"
    return None


def _expect_liquefaction_matches_its_hazus_terms(path):
    """Equation 4-9, re-derived from each susceptibility row's own terms.

    The other half of the same tool, and a completely different engine path:
    no DEM, no wetness index, no Vs30. The row carries the category it was
    read as, the conditional probability of Table 4-11, both correction
    factors and the settlement, so Equation 4-9 is checkable from the file
    itself: if the identity does not close, the run applied a factor the
    columns do not show, or looked the proportion up under the wrong category.

    Equation 4-11's feet conversion is checked too, against the depth the
    extra run was pinned to. That conversion is worth a real assertion at this
    level: passing metres where the published polynomial wants feet is a
    ~7 % error that every count and every schema check passes, and it is
    exactly the class of unit defect that has shipped here before.
    """
    from planx.engine import liquefaction

    names, rows, complaint = _read_gpkg(path)
    if complaint:
        return complaint
    required = {"liq_prob", "liq_cond_prob", "liq_cat", "k_m", "k_w",
                "liq_pga_t", "liq_settle_in", "pga_g", "mw", "liq_area_frac"}
    missing = required - set(names)
    if missing:
        return f"missing liquefaction column(s): {', '.join(sorted(missing))}"
    expected_k_w = liquefaction.hazus_groundwater_factor(_LIQ_GROUNDWATER_M)
    seen = set()
    for index, row in enumerate(rows, start=1):
        category = row["liq_cat"]
        if category is None:
            return f"row {index}: no category, so the row is not a Hazus result"
        seen.add(category)
        pga = float(row["pga_g"])
        conditional = float(row["liq_cond_prob"])
        k_m = float(row["k_m"])
        k_w = float(row["k_w"])
        if abs(conditional - liquefaction.hazus_conditional(category, pga)) > 1e-9:
            return (f"row {index}: the conditional probability is not Table 4-11 "
                    f"evaluated at {pga:g} g for '{category}'")
        if abs(k_w - expected_k_w) > 1e-9:
            return (f"row {index}: K_W is {k_w:.6f} where {_LIQ_GROUNDWATER_M:g} m "
                    f"gives {expected_k_w:.6f} - Equation 4-11 takes feet")
        if abs(k_m - liquefaction.hazus_magnitude_factor(float(row["mw"]))) > 1e-9:
            return (f"row {index}: K_M is not Equation 4-10 at Mw {row['mw']}")
        proportion = liquefaction.HAZUS_PROPORTION[category]
        identity = conditional / (k_m * k_w) * proportion
        if abs(float(row["liq_prob"]) - min(max(identity, 0.0), 1.0)) > 1e-9:
            return (f"row {index}: liq_prob {float(row['liq_prob']):.12f} does not "
                    f"close Equation 4-9 on the row's own conditional, K_M, K_W "
                    f"and the Table 4-10 proportion for '{category}' "
                    f"({identity:.12f})")
        threshold = liquefaction.HAZUS_PGA_THRESHOLD.get(category)
        stored = row["liq_pga_t"]
        if (stored is None) != (threshold is None):
            return (f"row {index}: '{category}' has threshold {threshold!r} but "
                    f"the row stores {stored!r}")
        if threshold is not None and abs(float(stored) - threshold) > 1e-9:
            return (f"row {index}: threshold {stored} is not Table 4-12's "
                    f"{threshold} for '{category}'")
        if abs(float(row["liq_settle_in"])
               - float(row["liq_prob"]) * liquefaction.HAZUS_SETTLEMENT_IN[category]) > 1e-9:
            return (f"row {index}: settlement is not the probability times the "
                    f"Table 4-13 amplitude for '{category}'")
        if row["liq_area_frac"] is not None:
            return (f"row {index}: liq_area_frac is filled in susceptibility mode, "
                    "where nothing computes a coverage reading")
    if len(seen) < len(liquefaction.HAZUS_CATEGORIES):
        return (f"the run only reached {len(seen)} of the six categories "
                f"({', '.join(sorted(seen))}), so the fixture is not exercising "
                "the table it was built for")
    if not rows:
        return f"{path} holds no row, so nothing was checked"
    return None


#: Value expectations for an extra run, keyed (algorithm id, extra label).
#: An extra run exists because it takes a branch the primary case never
#: reaches, and a branch that writes the right number of rows with the wrong
#: numbers passes every count-based check there is - including the primary
#: case's own value check, which says nothing about it.
EXTRA_VALUE_EXPECTATIONS = {
    ("planx:liquefaction", "susceptibility"): {
        "OUTPUT": _expect_liquefaction_matches_its_hazus_terms,
    },
}


#: Refusals that have to be made to happen, in real QGIS, on real layers.
#: (algorithm id, overrides applied on top of that tool's resolved inputs, a
#: substring the refusal must contain). Run after the sweep so the overrides
#: only have to name what changes; everything else is the same wiring a
#: passing case used, which is what stops a refusal passing for the wrong
#: reason - a parameter that was unusable anyway would refuse too.
REFUSALS = (
    # Rule R7. Hazus assumes no ground failure when it has no input; a tool
    # that assumed the same would answer "nothing liquefies here" for a map
    # unit nobody ever classified, which is the most dangerous answer this
    # family can give. The category column is cleared rather than absent so the
    # run reaches the refusal with an otherwise valid layer.
    ("planx:liquefaction",
     {"MODE": 1, "CATEGORY_FIELD": ""},
     "Susceptibility mode needs a map-unit layer"),
)


#: algorithm id -> callable(output path) -> complaint or None. Run only when
#: the ordinary output verification passed, so a complainer here is always
#: describing a wrong value rather than a missing output.
#:
#: A check reads its output with :func:`_read_gpkg`, never with a
#: ``QgsVectorLayer``: the harness re-creates destinations in its extra runs,
#: and an open QGIS datasource on a file stops Windows from replacing it.
VALUE_EXPECTATIONS = {
    "planx:groundmotion": {
        "OUTPUT": _expect_groundmotion_distances_are_kilometres,
    },
    "planx:seismicdebris": {
        "OUT_BUILDINGS": _expect_debris_volume_uses_the_reported_footprint,
    },
    "planx:seismicimpact": {
        "OUT": _expect_impact_casualties_conserve_occupants,
    },
    "planx:liquefaction": {
        "OUTPUT": _expect_liquefaction_matches_its_own_terms,
    },
}


def check_values(algorithm_id, produced):
    """Apply this tool's value expectations. Returns a complaint, or None."""
    for output_name, expectation in VALUE_EXPECTATIONS.get(algorithm_id, {}).items():
        path = produced.get(output_name)
        if path is None:
            continue
        complaint = expectation(path)
        if complaint:
            return f"{output_name}: {complaint}"
    return None


def check_extra_values(algorithm_id, label, produced):
    """The same, for one extra run's output. Returns a complaint, or None."""
    for output_name, expectation in \
            EXTRA_VALUE_EXPECTATIONS.get((algorithm_id, label), {}).items():
        path = produced.get(output_name)
        if path is None:
            continue
        complaint = expectation(path)
        if complaint:
            return f"{output_name}: {complaint}"
    return None


def verify_outputs(algorithm, produced, result, only=None):
    ok = True
    for definition in algorithm.parameterDefinitions():
        if not definition.isDestination():
            continue
        name = definition.name()
        if only is not None and name not in only:
            continue
        if not isinstance(definition, QgsProcessingParameterFileDestination) \
                and name not in produced:
            result.outputs[name] = "not returned by processing.run"
            ok = False
            continue
        path = produced.get(name)
        if path is None:
            result.outputs[name] = "not returned by processing.run"
            ok = False
            continue
        if isinstance(definition, QgsProcessingParameterFeatureSink):
            good, detail = _verify_vector(path)
        elif isinstance(definition, QgsProcessingParameterRasterDestination):
            good, detail = _verify_raster(path)
        else:
            good, detail = _verify_file(path)
        if not good and _is_optional(definition) \
                and (algorithm.id(), name) in CONDITIONAL_OUTPUTS:
            result.outputs[name] = f"conditional, absent: {detail}"
            continue
        result.outputs[name] = detail
        if not good:
            ok = False
    return ok


