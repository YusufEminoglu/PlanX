    def as_dict(self):
        return {
            "algorithm": self.algorithm_id,
            "display_name": self.display_name,
            "ok": self.ok,
            "seconds": round(self.seconds, 3),
            "error": self.error,
            "choices": self.choices,
            "outputs": self.outputs,
            "warnings": self.warnings,
            "info": self.info,
            "extra_info": self.extra_info,
        }


