def _verify_vector(path_or_layer):
    layer = (path_or_layer if isinstance(path_or_layer, QgsVectorLayer)
             else QgsVectorLayer(str(path_or_layer), "matrix_out", "ogr"))
    if not layer.isValid():
        return False, f"did not load as a vector layer: {path_or_layer}"
    count = layer.featureCount()
    if count <= 0:
        return False, f"empty vector output (0 features): {path_or_layer}"
    return True, f"{count} feature(s)"


def _verify_raster(path_or_layer):
    import numpy as np
    from osgeo import gdal

    layer = (path_or_layer if isinstance(path_or_layer, QgsRasterLayer)
             else QgsRasterLayer(str(path_or_layer), "matrix_out", "gdal"))
    if not layer.isValid():
        return False, f"did not load as a raster layer: {path_or_layer}"
    handle = gdal.Open(layer.source(), gdal.GA_ReadOnly)
    if handle is None:
        return False, f"GDAL could not open {layer.source()}"
    band = handle.GetRasterBand(1)
    array = band.ReadAsArray()
    nodata = band.GetNoDataValue()
    handle = None
    if array is None or array.size == 0:
        return False, "the raster band is empty"
    good = np.isfinite(array)
    if nodata is not None:
        good &= array != nodata
    populated = int(good.sum())
    if populated == 0:
        return False, "no finite, non-nodata pixel in the raster"
    return True, f"{populated}/{array.size} populated pixel(s)"


def _verify_file(path):
    target = Path(str(path))
    if not target.exists():
        return False, f"not written: {path}"
    if target.stat().st_size <= 0:
        return False, f"empty file: {path}"
    if target.suffix.lower() == ".json":
        try:
            with target.open(encoding="utf-8") as handle:
                json.load(handle)
        except (OSError, ValueError) as exc:
            return False, f"the JSON does not parse: {exc}"
    return True, f"{target.stat().st_size} byte(s)"


