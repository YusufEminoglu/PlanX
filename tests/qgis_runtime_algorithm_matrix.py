def _geometry_area(feature):
    geometry = feature.geometry()
    if geometry is None or geometry.isEmpty():
        return 0.0
    return float(geometry.area())


def _number(values, key, fallback):
    """A demo attribute by name. By name, not by position: a GeoPackage read
    back through OGR carries its own ``fid`` field ahead of the real ones."""
    value = values.get(key)
    return fallback if value is None else float(value)


def _network_attrs(index, _feature, values):
    length = _number(values, "length_m", 0.0)
    return [
        50.0,                                  # speed
        2.0,                                   # lanes
        1200.0,                                # aadt
        "mixed",                               # infra
        1 + index % 4,                         # lts
        800.0 + float((index * 137) % 900),    # volume
        0.35,                                  # emission
        length,                                # cost
        45.0 + float((index * 7) % 50),        # score
        4.0,                                   # heavy
        0,                                     # oneway
        length,                                # fwd_cost
        length,                                # rev_cost
        "residential",                         # highway
        8.0,                                   # width
    ]


def _building_attrs(index, _feature, values):
    height = _number(values, "height", 6.0)
    return [max(1, int(round(height / 3.0))), 1975 + (index * 3) % 50]


#: The occupancy fixture: what a real city's building layer looks like when it
#: has been prepared for a casualty run, rather than the bare geometry the demo
#: city generates. Cycled rather than random so a run is reproducible.
OCCUPANCY_EXTRA = (
    ("occupancy", STRING),
    ("population", DOUBLE),
    ("units", DOUBLE),
    ("damage_state", STRING),
)
_OCCUPANCY_CYCLE = (
    ("Residential", 1), ("Residential", 4), ("Commercial", 0),
    ("Primary school", 0), ("Industrial", 0), ("Hotel", 0),
)


def _occupancy_attrs(index, _feature, values):
    label, units = _OCCUPANCY_CYCLE[index % len(_OCCUPANCY_CYCLE)]
    floors = max(1, int(round(_number(values, "height", 6.0) / 3.0)))
    return [
        label,
        float(floors * 12),      # population: a screening count, not a survey
        float(units),
        # Cycling the damage state gives the certainty branch all five states,
        # including "none", rather than only the ones a single run would hit.
        ("none", "slight", "moderate", "extensive", "complete")[index % 5],
    ]


#: The six categories the liquefaction model's tables are written for, cycled
#: so one run touches all six branches. Spelled exactly as the model accepts
#: them, which is the point of the fixture: the land-use words an ordinary
#: city layer carries are *not* these, and the tool refuses them on purpose.
