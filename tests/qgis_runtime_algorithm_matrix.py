def _role(name):
    upper = name.upper()
    for token, role in ROLE_BY_PARAM:
        if token in upper:
            return role
    return None


def _pick_layer(algorithm_id, name):
    override = LAYER_OVERRIDES.get((algorithm_id, name))
    if override:
        return override, f"override:{override}"
    role = _role(name)
    if role is None:
        return None, ""
    return role, f"name:{name}->{role}"


def _pick_raster(name):
    for token, key in RASTER_BY_PARAM:
        if token in name.upper():
            return key, f"name:{name}->{key}"
    return "dsm", f"default:{name}->dsm"


def _load_tables(bundle):
    tables = {}
    for role, path in bundle["layers"].items():
        layer = QgsVectorLayer(str(path), role, "ogr")
        if not layer.isValid():
            raise RuntimeError(f"fixture '{role}' did not load from {path}")
        tables[role] = layer
    study = QgsVectorLayer(str(bundle["study_area"]), "study_area", "ogr")
    if not study.isValid():
        raise RuntimeError("study_area fixture did not load")
    tables["study_area"] = study

    rasters = {}
    for key, path in bundle["rasters"].items():
        layer = QgsRasterLayer(str(path), key, "gdal")
        if not layer.isValid():
            raise RuntimeError(f"fixture raster '{key}' did not load")
        rasters[key] = layer
    return tables, rasters


def _pick_field(name, parent_layer, parent_role):
    """A field that exists on ``parent_layer``.

    Raising is the point. A field parameter left unsupplied is reported by QGIS
    as a missing input, but a field *silently* bound to a name that is not in
    the layer makes the algorithm fall back to its own default - a green cell
    that tested nothing.
    """
    available = {field.name().lower(): field.name()
                 for field in parent_layer.fields()}

    if name in FIELD_LIST_OVERRIDES:
        wanted = FIELD_LIST_OVERRIDES[name]
        found = [available[item] for item in wanted if item in available]
        if not found:
            raise RuntimeError(
                f"'{name}' wants {wanted} on '{parent_role}', none present "
                f"(has {sorted(available)})")
        return found, f"list:{','.join(found)}"

    hint = FIELD_BY_PARAM.get(name)
    if hint and hint in available:
        return available[hint], f"hint:{hint}"
    raise RuntimeError(
        f"no fixture field for '{name}' on '{parent_role}' "
        f"(hint={hint!r}, fields={sorted(available)})")


def _destination_path(name, out_dir, algorithm_id):
    stem = f"{algorithm_id.split(':')[-1]}_{name}"
    upper = name.upper()
    if upper.endswith("HTML"):
        return str(Path(out_dir) / f"{stem}.html")
    if upper.endswith("JSON"):
        return str(Path(out_dir) / f"{stem}.json")
    return str(Path(out_dir) / f"{stem}.gpkg")


def _is_token(value):
    """True when a value names an artefact or fixture rather than a literal."""
    return value.startswith(("art:", "fixture:"))


def _resolve_special(token, artifacts, bundle):
    kind, _, key = token.partition(":")
    if kind == "art":
        if key not in artifacts:
            raise RuntimeError(f"artefact '{key}' has not been produced yet")
        return artifacts[key]
    if kind == "fixture":
        return bundle["files"][key]
    raise RuntimeError(f"unknown value token '{token}'")


def build_inputs(algorithm, bundle, tables, rasters, artifacts, out_dir, result):
    """Turn one algorithm's declared parameters into a concrete parameter dict."""
    algorithm_id = algorithm.id()
    values = {}
    for definition in algorithm.parameterDefinitions():
        name = definition.name()
        optional = _is_optional(definition)
        override = VALUE_OVERRIDES.get((algorithm_id, name))

        if definition.isDestination():
            values[name] = _destination_path(name, out_dir, algorithm_id)
            result.choices[name] = "destination"
            continue

        # An explicit decision outranks every heuristic below, whatever the
        # parameter type: many of these point a layer parameter at the artefact
        # of an earlier case, and a name-based guess would never find it.
        if override is not None:
            if isinstance(override, list):
                resolved = [_resolve_special(item, artifacts, bundle)
                            for item in override]
                values[name] = ";".join(str(item) for item in resolved)
            else:
                values[name] = _resolve_special(override, artifacts, bundle)
            result.choices[name] = f"override:{override}"
            continue

        if isinstance(definition, QgsProcessingParameterField):
            if optional and name in SKIP_OPTIONAL:
                result.choices[name] = "skipped(optional)"
                continue
            parent_role = result.choices.get(
                definition.parentLayerParameterName(), "").split("->")[-1]
            parent_role = parent_role.replace("override:", "")
            layer = tables.get(parent_role)
            if layer is None:
                if optional:
                    result.choices[name] = "skipped(no parent layer)"
                    continue
                raise RuntimeError(
                    f"'{name}' needs parent "
                    f"'{definition.parentLayerParameterName()}' "
                    f"(resolved to '{parent_role}'), which is not a fixture")
            field_name, why = _pick_field(name, layer, parent_role)
            values[name] = field_name
            result.choices[name] = f"{why}@{parent_role}"
            continue

        # QgsProcessingParameterVectorLayer is a sibling of FeatureSource, not a
        # subclass, so both need the same branch.
        if isinstance(definition, (QgsProcessingParameterFeatureSource,
                                   QgsProcessingParameterVectorLayer)):
            if optional and name in SKIP_OPTIONAL:
                result.choices[name] = "skipped(optional)"
                continue
            role, why = _pick_layer(algorithm_id, name)
            if role is None:
                if optional:
                    result.choices[name] = "skipped(no fixture)"
                    continue
                raise RuntimeError(f"no fixture for required layer '{name}'")
            values[name] = tables[role]
            result.choices[name] = why
            continue

        if isinstance(definition, QgsProcessingParameterMultipleLayers):
            roles = MULTI_OVERRIDES.get(name)
            if not roles:
                if optional:
                    result.choices[name] = "skipped(no fixture)"
                    continue
                raise RuntimeError(f"no fixture list for required '{name}'")
            values[name] = [tables[role] for role in roles]
            result.choices[name] = "multi:" + ",".join(roles)
            continue

        if isinstance(definition, QgsProcessingParameterRasterLayer):
            if optional and name in SKIP_OPTIONAL:
                result.choices[name] = "skipped(optional)"
                continue
            key, why = _pick_raster(name)
            values[name] = rasters[key]
            result.choices[name] = why
            continue

        if isinstance(definition, QgsProcessingParameterNumber):
            default = definition.defaultValue()
            values[name] = float(default if default is not None else 0.0)
            result.choices[name] = f"default:{values[name]:g}"
            continue

        if isinstance(definition, QgsProcessingParameterBoolean):
            values[name] = bool(definition.defaultValue())
            result.choices[name] = f"default:{values[name]}"
            continue

        if isinstance(definition, QgsProcessingParameterEnum):
            default = definition.defaultValue()
            values[name] = int(default if default is not None else 0)
            result.choices[name] = f"default:{values[name]}"
            continue

        if isinstance(definition, QgsProcessingParameterString):
            default = definition.defaultValue()
            if optional and default in (None, ""):
                result.choices[name] = "skipped(optional)"
                continue
            values[name] = "" if default is None else str(default)
            result.choices[name] = f"default:{values[name]!r}"
            continue

        if isinstance(definition, QgsProcessingParameterCrs):
            if optional and name in SKIP_OPTIONAL:
                result.choices[name] = "skipped(optional)"
                continue
            values[name] = QgsCoordinateReferenceSystem(CITY_CRS)
            result.choices[name] = f"crs:{CITY_CRS}"
            continue

        if isinstance(definition, QgsProcessingParameterExtent):
            result.choices[name] = "skipped(optional)"
            continue

        if isinstance(definition, QgsProcessingParameterDateTime):
            when = DATETIME_OVERRIDES.get(
                name, QDateTime(QDate(2026, 6, 21), QTime(12, 0)))
            values[name] = when
            result.choices[name] = f"datetime:{when.toString('yyyy-MM-dd HH:mm')}"
            continue

        if isinstance(definition, QgsProcessingParameterFile):
            if optional:
                result.choices[name] = "skipped(optional)"
                continue
            raise RuntimeError(f"no file fixture for '{name}'")

        # A new parameter type must fail loudly rather than be silently skipped.
        raise RuntimeError(
            f"unhandled parameter type {type(definition).__name__} for '{name}'")

    return values


