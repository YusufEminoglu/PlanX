def _new_context(transform_context, feedback):
    context = QgsProcessingContext()
    context.setProject(QgsProject.instance())
    context.setTransformContext(transform_context)
    context.setFeedback(feedback)
    return context


def _teardown(application):
    """Shut QGIS down, except on Windows where shutting it down is the hazard.

    OSGeo4W can access-violate during teardown after a few hundred temporary
    Processing layers even when every algorithm passed, and it can also block
    for minutes. The work is finished and the report is already out by then, so
    on Windows the process is short-circuited instead (``os._exit`` in
    :func:`main`); the same guard exists in the geostats matrix for the same
    reason.
    """
    if os.name == "nt":
        return
    try:
        application.exitQgis()
    except Exception:  # noqa: BLE001 - teardown must never change the verdict
        pass


def run_matrix(only=None, verbose=False, keep_work_dir=False):
    from processing.core.Processing import Processing

    from planx.provider import PlanXProvider

    application = QgsApplication([], True)
    application.initQgis()
    work_dir = tempfile.mkdtemp(prefix="planx_matrix_")
    results = []
    catalog_errors = []
    try:
        Processing.initialize()
        provider = PlanXProvider()
        QgsApplication.processingRegistry().addProvider(provider)
        import processing
        transform_context = QgsProject.instance().transformContext()

        started = time.time()
        bundle = build_fixtures(processing, work_dir, transform_context)
        fixture_seconds = time.time() - started
        tables, rasters = _load_tables(bundle)

        # Keyed by the qualified Processing id, not name(): name() is the bare
        # slug the manual anchors use, and processing.run() needs the id.
        algorithms = {algorithm.id(): algorithm
                      for algorithm in provider.algorithms()}
        unqualified = sorted(key for key in algorithms if ":" not in key)
        if unqualified:
            catalog_errors.append(
                f"{len(unqualified)} algorithm id(s) are not provider-qualified: "
                f"{unqualified[:5]}")
        if len(algorithms) < MIN_EXPECTED_CASE_COUNT:
            catalog_errors.append(
                f"the provider exposes {len(algorithms)} algorithms, "
                f"expected at least {MIN_EXPECTED_CASE_COUNT}")

        order = [name for name in RUN_FIRST if name in algorithms]
        order += [name for name in sorted(algorithms) if name not in order]
        if only:
            order = [name for name in order if name in only]
        elif len(order) != len(algorithms):
            catalog_errors.append(
                f"the sweep covers {len(order)} of {len(algorithms)} "
                f"registered algorithms")

        artifacts = {}
        inputs_by_id = {}
        for algorithm_id in order:
            algorithm = algorithms[algorithm_id]
            result = CaseResult(algorithm_id, algorithm.displayName())
            out_dir = Path(work_dir) / "outputs" / algorithm_id.split(":")[-1]
            out_dir.mkdir(parents=True, exist_ok=True)
            feedback = MatrixFeedback()
            context = _new_context(transform_context, feedback)
            values = {}
            begin = time.time()
            try:
                if algorithm_id == "planx:democity":
                    # Already executed to build the fixtures. Reuse that run so
                    # the city is generated once, and still judge the real
                    # outputs of a real execution.
                    produced = bundle["raw"]
                else:
                    values = build_inputs(algorithm, bundle, tables, rasters,
                                          artifacts, out_dir, result)
                    inputs_by_id[algorithm_id] = dict(values)
                    produced = processing.run(algorithm_id, values,
                                              context=context,
                                              feedback=feedback)
                result.ok = verify_outputs(algorithm, produced, result)
                if not result.ok:
                    result.error = "one or more outputs failed verification"
                else:
                    complaint = check_values(algorithm_id, produced)
                    if complaint:
                        result.ok = False
                        result.error = f"wrong value: {complaint}"
                    else:
                        # Only worth running the tool a second time on the same
                        # city elsewhere if it produced a well-formed answer
                        # here. A tool that failed its own outputs, or its own
                        # values, has said enough already, and comparing two
                        # runs of a broken tool reports noise.
                        complaint = _check_translation_invariance(
                            processing, algorithm, values, bundle,
                            Path(work_dir) / "translated"
                            / algorithm_id.split(":")[-1],
                            algorithm_id, transform_context)
                        if complaint:
                            result.ok = False
                            result.error = f"translation: {complaint}"
                for definition in algorithm.parameterDefinitions():
                    if definition.isDestination() and definition.name() in produced:
                        artifacts[f"{algorithm_id}/{definition.name()}"] = \
                            produced[definition.name()]
                for artifact_name, output_name, overrides in \
                        EXTRA_RUNS.get(algorithm_id, ()):
                    extra_dir = out_dir / f"extra_{artifact_name}"
                    extra_dir.mkdir(parents=True, exist_ok=True)
                    extra = dict(values)
                    extra.update(overrides)
                    # A token, not a literal: the overrides go through the same
                    # resolver as the primary inputs, so an extra run can read an
                    # artefact an earlier extra run produced.
                    for key, value in overrides.items():
                        if isinstance(value, str) and _is_token(value):
                            extra[key] = _resolve_special(value, artifacts, bundle)
                    extra[output_name] = _destination_path(
                        output_name, extra_dir, algorithm_id)
                    extra_feedback = MatrixFeedback()
                    extra_produced = processing.run(
                        algorithm_id, extra,
                        context=_new_context(transform_context, extra_feedback),
                        feedback=extra_feedback)
                    artifacts[f"extra/{artifact_name}"] = \
                        extra_produced[output_name]
                    # Verified like the primary run. An extra run that writes
                    # an empty output tested nothing, and counting it as
                    # coverage because the primary case passed is exactly how a
                    # whole network source goes untested while looking green.
                    extra_result = CaseResult(algorithm_id,
                                              algorithm.displayName())
                    if not verify_outputs(algorithm, extra_produced,
                                          extra_result, only={output_name}):
                        result.ok = False
                        result.error = _and_also(result.error, (
                            f"extra run '{artifact_name}' failed verification: "
                            f"{extra_result.outputs.get(output_name, '')}"))
                    else:
                        complaint = check_extra_values(
                            algorithm_id, artifact_name, extra_produced)
                        if complaint:
                            result.ok = False
                            result.error = _and_also(result.error, (
                                f"extra run '{artifact_name}' wrong value: "
                                f"{complaint}"))
                    result.extra_info[artifact_name] = [
                        f"{output_name}: "
                        f"{extra_result.outputs.get(output_name, 'no output')}"
                    ] + extra_feedback.info[:20]
            except Exception as exc:  # noqa: BLE001 - the verdict is the report
                result.ok = False
                result.error = f"{type(exc).__name__}: {exc}"
                if verbose:
                    traceback.print_exc()
            result.seconds = time.time() - begin
            result.warnings = feedback.warnings[:20]
            # What the algorithm said it did. This is the evidence behind a
            # green cell that a count alone cannot give - a tool that reports
            # "Scored metrics: 0" produced a well-formed empty answer, and the
            # report should say so rather than let the output count imply more.
            result.info = feedback.info[:40]
            results.append(result)
            if verbose:
                mark = "ok  " if result.ok else "FAIL"
                print(f"  {mark} {algorithm_id:34s} {result.seconds:7.2f}s "
                      f"{result.error}", flush=True)

        # The refusals, after the sweep so they can re-use resolved inputs.
        for algorithm_id, overrides, expected in REFUSALS:
            if only and algorithm_id not in only:
                continue
            algorithm = algorithms.get(algorithm_id)
            base = inputs_by_id.get(algorithm_id)
            result = CaseResult(algorithm_id, f"{expected} (refusal)")
            result.choices = {f"refusal:{key}": str(value)
                              for key, value in overrides.items()}
            if algorithm is None or base is None:
                result.error = ("the algorithm did not run in the sweep, so its "
                                "refusal has no inputs to stand on")
                results.append(result)
                continue
            values = dict(base)
            for key, value in overrides.items():
                values[key] = value
            begin = time.time()
            try:
                processing.run(algorithm_id, values,
                               context=_new_context(transform_context,
                                                    MatrixFeedback()),
                               feedback=MatrixFeedback())
            except Exception as exc:  # noqa: BLE001 - the verdict is the report
                result.seconds = time.time() - begin
                if expected in str(exc):
                    result.ok = True
                else:
                    result.error = (f"refused, but not for the stated reason: "
                                    f"{type(exc).__name__}: {exc}")
            else:
                result.seconds = time.time() - begin
                result.error = ("the run completed where it was supposed to "
                                f"stop, so {algorithm_id} answered a question "
                                "it has no input for")
            results.append(result)
            if verbose:
                mark = "ok  " if result.ok else "FAIL"
                print(f"  {mark} {algorithm_id} refusal "
                      f"{result.seconds:7.2f}s {result.error}", flush=True)
    finally:
        # --keep leaves the fixtures and the outputs in place, because the
        # report names their paths: a failing case is diagnosed by measuring the
        # file it wrote, and an earlier version of this file deleted that file
        # (and, on Windows, half of the fixture directory with it - the GPKGs a
        # live QgsVectorLayer still holds cannot be removed) a few lines after
        # printing where to find it.
        if not keep_work_dir:
            shutil.rmtree(work_dir, ignore_errors=True)
        _teardown(application)

    ok_count = sum(1 for item in results if item.ok)
    payload = {
        "qgis_version": Qgis.version(),
        "qgis_release": Qgis.releaseName(),
        "fixture_seconds": round(fixture_seconds, 3),
        "case_count": len(results),
        "ok_count": ok_count,
        "failed_count": len(results) - ok_count,
        "catalog_errors": catalog_errors,
        "failed": [{"algorithm": item.algorithm_id, "error": item.error,
                    "choices": item.choices, "outputs": item.outputs}
                   for item in results if not item.ok],
        "cases": [item.as_dict() for item in results],
    }
    if keep_work_dir:
        payload["work_dir"] = str(work_dir)
    return payload


def main(argv=None):
    parser = argparse.ArgumentParser(description="PlanX runtime algorithm matrix")
    parser.add_argument("--only", action="append",
                        help="restrict the sweep to this algorithm id "
                             "(repeatable; mainly for timing one tool)")
    parser.add_argument("--verbose", action="store_true",
                        help="print one line per case as it runs")
    parser.add_argument("--report", help="write the full JSON report here")
    parser.add_argument("--keep", action="store_true",
                        help="keep the fixture and output files and name their "
                             "directory in the report, so a failing case can be "
                             "measured rather than guessed at")
    args = parser.parse_args(argv)

    payload = run_matrix(only=set(args.only) if args.only else None,
                         verbose=args.verbose, keep_work_dir=args.keep)
    if args.report:
        Path(args.report).write_text(
            json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
    print("PLANX_RUNTIME_MATRIX_JSON=" + json.dumps(payload, sort_keys=True))
    verdict = "PASS" if (payload["failed_count"] == 0
                         and not payload["catalog_errors"]) else "FAIL"
    print(f"PLANX_RUNTIME_MATRIX: {verdict} "
          f"({payload['ok_count']}/{payload['case_count']})")
    for problem in payload["catalog_errors"]:
        print(f"  catalog: {problem}")
    sys.stdout.flush()
    # QGIS teardown on Windows can block for minutes after the work is done and
    # the report is out; the process is finished either way.
    os._exit(0 if verdict == "PASS" else 1)


if __name__ == "__main__":
    main()
