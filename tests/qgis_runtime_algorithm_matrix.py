def _geometry_area(feature):
    geometry = feature.geometry()
    if geometry is None or geometry.isEmpty():
        return 0.0
    return float(geometry.area())


def _number(values, key, fallback):
    """A demo attribute by name. By name, not by position: a GeoPackage read
    back through OGR carries its own ``fid`` field ahead of the real ones."""
    value = values.get(key)
    return fallback if value is None else float(value)


def _network_attrs(index, _feature, values):
    length = _number(values, "length_m", 0.0)
    return [
        50.0,                                  # speed
        2.0,                                   # lanes
        1200.0,                                # aadt
        "mixed",                               # infra
        1 + index % 4,                         # lts
        800.0 + float((index * 137) % 900),    # volume
        0.35,                                  # emission
        length,                                # cost
        45.0 + float((index * 7) % 50),        # score
        4.0,                                   # heavy
        0,                                     # oneway
        length,                                # fwd_cost
        length,                                # rev_cost
        "residential",                         # highway
        8.0,                                   # width
    ]


def _building_attrs(index, _feature, values):
    height = _number(values, "height", 6.0)
    return [max(1, int(round(height / 3.0))), 1975 + (index * 3) % 50]


def _landuse_attrs(index, feature, values):
    use = str(values.get("use") or "other").lower()
    suit = {
        "residential": (0.8, 0.1, 0.1),
        "commercial": (0.1, 0.9, 0.1),
        "green": (0.05, 0.05, 0.95),
    }.get(use, (0.3, 0.3, 0.3))
    return [
        use,                       # category
        _geometry_area(feature),   # area_m2
        1.5,                       # far
        suit[0],                   # s_residential
        suit[1],                   # s_commercial
        suit[2],                   # s_green
        0,                         # lock
        40.0,                      # capacity
        1.0,                       # weight
        0.0,                       # existing
        index % 4,                 # district
    ]


def _demand_attrs(index, _feature, values):
    pop = _number(values, "pop", 1.0)
    return [
        pop,                     # value
        "all",                   # category
        index,                   # zone_id
        pop * 1.5,               # production
        pop * 2.0,               # attraction
        float(index + 1),        # rank
        int(pop * 0.8),          # jobs
        index + 1,               # origin_id
        index + 1,               # dest_id
        25 + (index * 7) % 50,   # age
        0.95,                    # survival
        0.45,                    # fertility
        0.0,                     # migration
        50.0 + float((index * 5) % 40),   # score
        pop * 4.0,               # dens_ha
    ]


def _poi_attrs(index, _feature, _values):
    return [1.0, index + 1]


def _facility_attrs(index, _feature, values):
    return [index + 1, _number(values, "cap", 100.0), 1000.0, 0.0, index + 1]


def _green_attrs(_index, feature, _values):
    return [_geometry_area(feature)]


def _flows_attrs(index, _feature, values):
    length = _number(values, "length_m", 0.0)
    return [
        500.0 + float((index * 61) % 400),   # flow
        2.0 + float(index % 5) * 0.5,        # time_car
        5.0 + float(index % 7) * 1.0,        # time_transit
        length,                              # cost
    ]


