class MatrixFeedback(QgsProcessingFeedback):
    """Feedback that keeps what the algorithm said, for the report."""

    def __init__(self):
        super().__init__()
        self.info = []
        self.warnings = []

    def pushInfo(self, message):  # noqa: N802 - Qt naming
        self.info.append(str(message))

    def pushWarning(self, message):  # noqa: N802 - Qt naming
        self.warnings.append(str(message))


class CaseResult:
    """One algorithm's verdict, plus the wiring that produced it."""

    def __init__(self, algorithm_id, display_name):
        self.algorithm_id = algorithm_id
        self.display_name = display_name
        self.ok = False
        self.seconds = 0.0
        self.error = ""
        self.choices = {}
        self.outputs = {}
        self.warnings = []
        self.info = []
        # Keyed by extra-run name. An extra run is a second execution whose
        # account would otherwise be thrown away, leaving the artefact it
        # produced as the only evidence that it did anything.
        self.extra_info = {}

    def as_dict(self):
        return {
            "algorithm": self.algorithm_id,
            "display_name": self.display_name,
            "ok": self.ok,
            "seconds": round(self.seconds, 3),
            "error": self.error,
            "choices": self.choices,
            "outputs": self.outputs,
            "warnings": self.warnings,
            "info": self.info,
            "extra_info": self.extra_info,
        }


